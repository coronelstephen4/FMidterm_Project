function phoneFormParts(string $storedNumber): array {
    $countries = countryPhoneOptions();
    $digits = preg_replace('/\D+/', '', $storedNumber) ?? '';

    if (preg_match('/^09[0-9]{9}$/', $digits)) {
        return ['country_iso' => 'PH', 'national_number' => substr($digits, 1), 'supported' => true];
    }

    if (str_starts_with($storedNumber, '+')) {
        $matches = [];
        foreach ($countries as $iso => $country) {
            if (str_starts_with($digits, $country['dial_code'])) {
                $matches[] = ['country_iso' => $iso, 'national_number' => substr($digits, strlen($country['dial_code'])), 'supported' => true];
            }
        }
        if ($matches) {
            usort($matches, static fn(array $a, array $b): int => strlen($countries[$b['country_iso']]['dial_code']) <=> strlen($countries[$a['country_iso']]['dial_code']));
            return $matches[0];
        }
    }

    return ['country_iso' => 'PH', 'national_number' => $storedNumber, 'supported' => false];
}

function phoneDisplayValue(string $storedNumber): string {
    $parts = phoneFormParts($storedNumber);
    if (!$parts['supported']) {
        return $storedNumber;
    }
    $country = countryPhoneOptions()[$parts['country_iso']] ?? null;
    if (!$country) {
        return $storedNumber;
    }

    $digits = preg_replace('/\D+/', '', $parts['national_number']) ?? '';
    if ($digits === '') {
        return $storedNumber;
    }

    if (strlen($digits) === 10) {
        $digits = substr($digits, 0, 3) . ' ' . substr($digits, 3, 3) . ' ' . substr($digits, 6);
    } elseif (strlen($digits) === 9) {
        $digits = substr($digits, 0, 3) . ' ' . substr($digits, 3, 3) . ' ' . substr($digits, 6);
    }

    return $country['flag'] . ' +' . $country['dial_code'] . ' ' . $digits;
}
