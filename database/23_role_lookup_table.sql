-- Add a normalized role lookup and connect each application account to it.
-- This migration copies every existing users.role value to users.role_id,
-- verifies the mapping, then drops the old text column in the same transaction.

BEGIN;

CREATE TABLE IF NOT EXISTS public.roles (
    role_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT roles_name_not_blank CHECK (BTRIM(role_name) <> ''),
    CONSTRAINT roles_allowed_names CHECK (role_name IN ('admin', 'staff'))
);

INSERT INTO public.roles (role_name)
VALUES ('admin'), ('staff')
ON CONFLICT (role_name) DO NOTHING;

ALTER TABLE public.users
    ADD COLUMN IF NOT EXISTS role_id INTEGER;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'users'
          AND column_name = 'role'
    ) THEN
        IF EXISTS (
            SELECT 1
            FROM public.users AS u
            LEFT JOIN public.roles AS r
              ON r.role_name = LOWER(BTRIM(u.role))
            WHERE r.role_id IS NULL
        ) THEN
            RAISE EXCEPTION 'Migration stopped: a user has an unrecognized role. Review users.role before retrying.';
        END IF;

        UPDATE public.users AS u
        SET role_id = r.role_id
        FROM public.roles AS r
        WHERE r.role_name = LOWER(BTRIM(u.role));
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.users AS u
        LEFT JOIN public.roles AS r ON r.role_id = u.role_id
        WHERE r.role_id IS NULL
    ) THEN
        RAISE EXCEPTION 'Migration stopped: every user must map to a role before the old role column is removed.';
    END IF;
END $$;

ALTER TABLE public.users
    ALTER COLUMN role_id SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'users_role_id_fkey'
          AND conrelid = 'public.users'::regclass
    ) THEN
        ALTER TABLE public.users
            ADD CONSTRAINT users_role_id_fkey
            FOREIGN KEY (role_id)
            REFERENCES public.roles (role_id)
            ON UPDATE CASCADE
            ON DELETE RESTRICT;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS users_role_id_idx
    ON public.users (role_id);

ALTER TABLE public.users
    DROP COLUMN IF EXISTS role;

ALTER TABLE public.roles ENABLE ROW LEVEL SECURITY;

COMMIT;

-- Verify the relationship and role assignments after running this script.
SELECT r.role_name, COUNT(u.user_id) AS user_count
FROM public.roles AS r
LEFT JOIN public.users AS u ON u.role_id = r.role_id
GROUP BY r.role_id, r.role_name
ORDER BY r.role_id;

SELECT
    EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'users_role_id_fkey'
          AND conrelid = 'public.users'::regclass
          AND contype = 'f'
    ) AS role_foreign_key_installed,
    NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'users'
          AND column_name = 'role'
    ) AS old_role_column_removed_after_copy,
    NOT EXISTS (
        SELECT 1
        FROM public.users AS u
        LEFT JOIN public.roles AS r ON r.role_id = u.role_id
        WHERE r.role_id IS NULL
    ) AS every_user_has_a_valid_role;
