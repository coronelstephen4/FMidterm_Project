-- Split CROP into CROP + CROP_VARIETY.
-- Existing crop_id values become variety_id values so planting links are preserved.
-- Review the preflight checks and take a backup before running in Supabase.

BEGIN;

-- This is a one-time migration. Make reruns stop before touching data.
DO $migration$
BEGIN
  IF to_regclass('public.crop_variety') IS NOT NULL THEN
    RAISE EXCEPTION 'Crop 3NF migration already appears to be applied; do not rerun this script.';
  END IF;

  IF NOT EXISTS (
       SELECT 1 FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = 'crop' AND column_name = 'variety'
     )
     OR NOT EXISTS (
       SELECT 1 FROM information_schema.columns
       WHERE table_schema = 'public' AND table_name = 'planting' AND column_name = 'crop_id'
     ) THEN
    RAISE EXCEPTION 'Expected the pre-migration crop and planting columns; stop and inspect the schema.';
  END IF;
END;
$migration$;

-- Stop before changing anything if merging normalized crop names would merge
-- different categories or create duplicate varieties under one crop.
DO $migration$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.crop
    GROUP BY lower(btrim(crop_name))
    HAVING count(DISTINCT crop_category_id) > 1
  ) THEN
    RAISE EXCEPTION 'Migration stopped: duplicate normalized crop names have different crop categories.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.crop
    GROUP BY lower(btrim(crop_name)), lower(btrim(variety))
    HAVING count(*) > 1
  ) THEN
    RAISE EXCEPTION 'Migration stopped: duplicate normalized crop and variety pairs exist.';
  END IF;
END;
$migration$;

CREATE TABLE public.crop_variety (
  variety_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crop_id integer NOT NULL,
  variety_name varchar(80) NOT NULL CHECK (btrim(variety_name) <> ''),
  growing_period_days integer NOT NULL CHECK (growing_period_days > 0),
  recommended_season_id smallint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT crop_variety_crop_id_fkey
    FOREIGN KEY (crop_id) REFERENCES public.crop(crop_id),
  CONSTRAINT crop_variety_season_fkey
    FOREIGN KEY (recommended_season_id)
    REFERENCES public.recommended_seasons(recommended_season_id)
);
ALTER TABLE public.crop_variety ENABLE ROW LEVEL SECURITY;

INSERT INTO public.crop_variety
  (variety_id, crop_id, variety_name, growing_period_days,
   recommended_season_id, created_at, updated_at)
OVERRIDING SYSTEM VALUE
SELECT c.crop_id, m.master_id, c.variety, c.growing_period_days,
       c.recommended_season_id, c.created_at, c.updated_at
FROM public.crop c
JOIN (
  SELECT crop_id AS old_id,
         MIN(crop_id) OVER (PARTITION BY lower(btrim(crop_name))) AS master_id
  FROM public.crop
) m ON m.old_id = c.crop_id;

SELECT setval(
  pg_get_serial_sequence('public.crop_variety', 'variety_id'),
  COALESCE((SELECT MAX(variety_id) FROM public.crop_variety), 1),
  EXISTS (SELECT 1 FROM public.crop_variety)
);

-- These guards read the columns being renamed or removed. Remove their
-- triggers before the schema changes; the planting guard is restored below.
DROP TRIGGER crop_duplicate_guard ON public.crop;
DROP TRIGGER planting_duplicate_guard ON public.planting;

ALTER TABLE public.planting DROP CONSTRAINT planting_crop_id_fkey;
ALTER TABLE public.planting RENAME COLUMN crop_id TO variety_id;
ALTER TABLE public.planting
  ADD CONSTRAINT planting_variety_id_fkey
  FOREIGN KEY (variety_id) REFERENCES public.crop_variety(variety_id);
CREATE INDEX planting_variety_id_idx ON public.planting(variety_id);

-- Remove duplicate crop master rows only after every old crop row has been
-- copied to crop_variety and planting IDs now reference those variety rows.
DELETE FROM public.crop
WHERE crop_id NOT IN (
  SELECT MIN(crop_id)
  FROM public.crop
  GROUP BY lower(btrim(crop_name))
);

ALTER TABLE public.crop
  DROP COLUMN variety,
  DROP COLUMN growing_period_days,
  DROP COLUMN recommended_season_id;

ALTER TABLE public.crop
  ADD CONSTRAINT crop_name_unique UNIQUE (crop_name);
CREATE UNIQUE INDEX crop_name_normalized_unique
  ON public.crop (lower(btrim(crop_name)));
CREATE UNIQUE INDEX crop_variety_name_normalized_unique
  ON public.crop_variety (crop_id, lower(btrim(variety_name)));

-- Keep the normalized crop-name duplicate guard without the removed variety column.
CREATE OR REPLACE FUNCTION public.reject_duplicate_crop()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF TG_OP = 'UPDATE' AND
       lower(btrim(NEW.crop_name)) = lower(btrim(OLD.crop_name)) THEN
        RETURN NEW;
    END IF;

    PERFORM pg_advisory_xact_lock(881003);

    IF EXISTS (
        SELECT 1 FROM public.crop AS other
        WHERE other.crop_id <> COALESCE(NEW.crop_id, -1)
          AND lower(btrim(other.crop_name)) = lower(btrim(NEW.crop_name))
    ) THEN
        RAISE EXCEPTION 'This crop name already exists.'
            USING ERRCODE = '23505', CONSTRAINT = 'crop_duplicate_guard';
    END IF;

    RETURN NEW;
END;
$function$;

CREATE TRIGGER crop_duplicate_guard
BEFORE INSERT OR UPDATE OF crop_name ON public.crop
FOR EACH ROW EXECUTE FUNCTION public.reject_duplicate_crop();

-- Restore the planting duplicate guard against the renamed FK column.
CREATE OR REPLACE FUNCTION public.reject_duplicate_planting()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF ROW(NEW.farm_id, NEW.variety_id, NEW.planting_date, NEW.area_planted,
               NEW.seed_quantity, NEW.expected_harvest_date, NEW.status_id)
           IS NOT DISTINCT FROM
           ROW(OLD.farm_id, OLD.variety_id, OLD.planting_date, OLD.area_planted,
               OLD.seed_quantity, OLD.expected_harvest_date, OLD.status_id) THEN
            RETURN NEW;
        END IF;
    END IF;

    PERFORM pg_advisory_xact_lock(881004);

    IF EXISTS (
        SELECT 1 FROM public.planting AS other
        WHERE other.planting_id <> COALESCE(NEW.planting_id, -1)
          AND ROW(other.farm_id, other.variety_id, other.planting_date,
                  other.area_planted, other.seed_quantity,
                  other.expected_harvest_date, other.status_id)
              IS NOT DISTINCT FROM
              ROW(NEW.farm_id, NEW.variety_id, NEW.planting_date,
                  NEW.area_planted, NEW.seed_quantity,
                  NEW.expected_harvest_date, NEW.status_id)
    ) THEN
        RAISE EXCEPTION 'An identical planting record already exists.'
            USING ERRCODE = '23505', CONSTRAINT = 'planting_duplicate_guard';
    END IF;

    RETURN NEW;
END;
$function$;

CREATE TRIGGER planting_duplicate_guard
BEFORE INSERT OR UPDATE OF farm_id, variety_id, planting_date, area_planted,
  seed_quantity, expected_harvest_date, status_id
ON public.planting
FOR EACH ROW EXECUTE FUNCTION public.reject_duplicate_planting();

CREATE TRIGGER crop_variety_set_updated_at
BEFORE UPDATE ON public.crop_variety
FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

COMMIT;

